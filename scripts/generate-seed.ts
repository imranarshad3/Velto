// Generates supabase/seed.sql from the bundled DEMO catalogue: `node scripts/generate-seed.ts`.
import { writeFileSync } from 'node:fs'
import { catalog } from '../src/data/catalog.ts'

const q = (v: string) => `'${v.replace(/'/g, "''")}'`
const arr = (a: string[]) => `array[${a.map(q).join(', ')}]::text[]`

const rows = catalog.map(
  (p, i) =>
    `  (${q(p.slug)}, ${q(p.name)}, ${q(p.categorySlug)}, ${q(p.usage)}, ${arr(p.applications)}, ${arr(p.areas)}, ${
      p.image ? `${q(JSON.stringify(p.image))}::jsonb` : 'null'
    }, false, true, ${i})`,
)

writeFileSync(
  new URL('../supabase/seed.sql', import.meta.url),
  `-- DEMO catalogue (generic product types, unverified). Generated by scripts/generate-seed.ts.
-- Safe to re-run: existing slugs are left untouched so admin edits are never overwritten.
insert into public.products (slug, name, category_slug, usage, applications, areas, image, verified, published, sort_order) values
${rows.join(',\n')}
on conflict (slug) do nothing;
`,
)
console.log(`seed.sql: ${rows.length} products`)
